"""Renders an audit pack as CSV or PDF (ALG4-237). Pure functions: content in, bytes out."""

import csv
import datetime
import io
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    KeepTogether,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from src.audit_packs.content import (
    AuditPackContent,
    Fields,
    Kind,
    Note,
    Value,
)
from src.audit_packs.content import Table as TableBlock

# --- CSV ----------------------------------------------------------------------------------------------------------

_CSV_UNITS = {Kind.MONEY: " (EUR)", Kind.PERCENT: " (%)"}


def _csv_number(number: float) -> str:
    if isinstance(number, float):
        return str(int(number)) if number.is_integer() else str(round(number, 2))
    return str(number)


def _csv_value(value: Value) -> str:
    raw = value.raw
    if raw is None:
        return ""
    if value.kind is Kind.LIST:
        return "; ".join(str(item) for item in raw)
    if isinstance(raw, bool):
        return "true" if raw else "false"
    if isinstance(raw, datetime.datetime):
        return raw.astimezone(datetime.UTC).isoformat().replace("+00:00", "Z")
    if isinstance(raw, int | float):
        return _csv_number(raw)
    return str(raw)


def render_csv(content: AuditPackContent) -> bytes:
    """One row per value: `section,field,value`. UTF-8 with a BOM, so Excel shows € and accents correctly.

    Numbers are plain (`300000`, `92.3`); the unit is in the field name (`Loan amount (EUR)`). Table rows are
    written as one row each: the first column is the field, the other columns are `name: value` pairs.
    """
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\r\n")
    writer.writerow(["section", "field", "value"])
    writer.writerow(["Audit pack", "Title", content.title])
    writer.writerow(["Audit pack", "Subject", content.subtitle])
    writer.writerow(
        [
            "Audit pack",
            "Generated at",
            _csv_value(Value(content.generated_at, Kind.DATETIME)),
        ]
    )
    writer.writerow(["Audit pack", "Generated by", content.generated_by_id])
    writer.writerow(["Audit pack", "Fingerprint (SHA-256)", content.fingerprint])

    for block in content.blocks:
        if isinstance(block, Fields):
            for label, value in block.rows:
                writer.writerow(
                    [
                        block.title,
                        label + _CSV_UNITS.get(value.kind, ""),
                        _csv_value(value),
                    ]
                )
        elif isinstance(block, TableBlock):
            if not block.rows:
                writer.writerow([block.title, "", block.empty_text])
            for row in block.rows:
                rest = "; ".join(
                    f"{column}: {_csv_value(cell)}"
                    for column, cell in zip(block.columns[1:], row[1:], strict=True)
                )
                writer.writerow([block.title, _csv_value(row[0]), rest])
        elif isinstance(block, Note):
            writer.writerow([block.title, "", block.text])

    return ("﻿" + buffer.getvalue()).encode("utf-8")


# --- PDF ----------------------------------------------------------------------------------------------------------

INK = colors.HexColor("#173b2a")
MUTED = colors.HexColor("#5d7568")
FOREST = colors.HexColor("#1f6b45")
LINE = colors.HexColor("#cfe0d4")
MIST = colors.HexColor("#e7f1ea")
EMPTY = "—"  # em dash

_STYLES = {
    "title": ParagraphStyle(
        "title", fontName="Helvetica-Bold", fontSize=18, leading=22, textColor=INK
    ),
    "subtitle": ParagraphStyle(
        "subtitle", fontName="Helvetica", fontSize=11, leading=14, textColor=INK
    ),
    "meta": ParagraphStyle(
        "meta", fontName="Helvetica", fontSize=8.5, leading=11, textColor=MUTED
    ),
    "heading": ParagraphStyle(
        "heading",
        fontName="Helvetica-Bold",
        fontSize=11.5,
        leading=14,
        textColor=FOREST,
        spaceBefore=10,
        spaceAfter=4,
    ),
    "label": ParagraphStyle(
        "label", fontName="Helvetica", fontSize=9, leading=11.5, textColor=MUTED
    ),
    "cell": ParagraphStyle(
        "cell",
        fontName="Helvetica",
        fontSize=9,
        leading=11.5,
        textColor=INK,
        alignment=TA_LEFT,
    ),
    "head": ParagraphStyle(
        "head", fontName="Helvetica-Bold", fontSize=8.5, leading=11, textColor=INK
    ),
    "body": ParagraphStyle(
        "body", fontName="Helvetica", fontSize=9, leading=12, textColor=INK
    ),
}


def _pdf_number(number: float, decimals: int = 2) -> str:
    if isinstance(number, float) and not number.is_integer():
        return f"{number:,.{decimals}f}"
    return f"{int(number):,}"


def _pdf_value(value: Value) -> str:
    raw = value.raw
    if raw is None or (value.kind is Kind.LIST and not raw):
        return EMPTY
    match value.kind:
        case Kind.MONEY if isinstance(raw, int | float):
            return f"€{_pdf_number(raw)}"
        case Kind.PERCENT if isinstance(raw, int | float):
            return f"{_pdf_number(round(raw, 1), 1)}%"
        case Kind.NUMBER if isinstance(raw, int | float):
            return _pdf_number(raw)
        case Kind.LIST:
            return "\n".join(f"• {item}" for item in raw)
    if isinstance(raw, bool):
        return "Yes" if raw else "No"
    if isinstance(raw, datetime.datetime):
        return raw.astimezone(datetime.UTC).strftime("%d %b %Y, %H:%M UTC")
    return str(raw)


def _paragraph(text: str, style: str) -> Paragraph:
    return Paragraph(escape(text).replace("\n", "<br/>"), _STYLES[style])


def _fields_table(block: Fields, width: float) -> Table:
    rows = [
        [_paragraph(label, "label"), _paragraph(_pdf_value(value), "cell")]
        for label, value in block.rows
    ]
    table = Table(rows, colWidths=[52 * mm, width - 52 * mm])
    table.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LINEBELOW", (0, 0), (-1, -1), 0.4, LINE),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                ("LEFTPADDING", (0, 0), (-1, -1), 0),
            ]
        )
    )
    return table


def _data_table(block: TableBlock, width: float) -> Table:
    if not block.rows:
        return Table([[_paragraph(block.empty_text, "label")]], colWidths=[width])

    narrow = 10 * mm  # the "#" column
    widths = {
        "#": narrow,
        "Status": 42 * mm,
        "Changed at": 42 * mm,
        "Model": 26 * mm,
        "Vote": 34 * mm,
        "Agent": 30 * mm,
    }
    fixed = sum(widths.get(column, 0) for column in block.columns)
    flexible = [column for column in block.columns if column not in widths]
    rest = (width - fixed) / max(1, len(flexible))
    col_widths = [widths.get(column, rest) for column in block.columns]

    rows = [[_paragraph(column, "head") for column in block.columns]]
    rows += [
        [_paragraph(_pdf_value(cell), "cell") for cell in row] for row in block.rows
    ]
    table = Table(rows, colWidths=col_widths, repeatRows=1)
    table.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("BACKGROUND", (0, 0), (-1, 0), MIST),
                ("LINEBELOW", (0, 0), (-1, -1), 0.4, LINE),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ]
        )
    )
    return table


def render_pdf(content: AuditPackContent) -> bytes:
    """A4 document: title, generation details, then one section per block; fingerprint and page number in the footer."""
    buffer = io.BytesIO()
    margin = 18 * mm
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=margin,
        rightMargin=margin,
        topMargin=margin,
        bottomMargin=margin + 4 * mm,
        title=f"{content.title}: {content.subtitle}",
        author="Agentic Lender (AL-Core)",
        subject="Lending decision audit pack",
    )
    width = A4[0] - 2 * margin
    generated = _pdf_value(Value(content.generated_at, Kind.DATETIME))

    story: list = [
        _paragraph(content.title, "title"),
        Spacer(1, 2 * mm),
        _paragraph(content.subtitle, "subtitle"),
        Spacer(1, 1.5 * mm),
        _paragraph(f"Generated {generated} by {content.generated_by_id}", "meta"),
        Spacer(1, 2 * mm),
    ]
    for block in content.blocks:
        heading = _paragraph(block.title, "heading")
        if isinstance(block, Fields):
            story.append(KeepTogether([heading, _fields_table(block, width)]))
        elif isinstance(block, TableBlock):
            story += [heading, _data_table(block, width)]
        elif isinstance(block, Note):
            story.append(KeepTogether([heading, _paragraph(block.text, "body")]))

    def footer(canvas, document) -> None:
        canvas.saveState()
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(MUTED)
        canvas.drawString(margin, 10 * mm, f"SHA-256 {content.fingerprint}")
        canvas.drawRightString(A4[0] - margin, 10 * mm, f"Page {document.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buffer.getvalue()
